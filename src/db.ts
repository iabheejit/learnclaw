function assertColumnsExist(
  database: Database.Database,
  tableName: string,
  expectedColumns: string[],
): void {
  const rows = database
    .prepare(`PRAGMA table_info(${tableName})`)
    .all() as Array<{ name: string }>;
  const present = new Set(rows.map((r) => r.name));
  const missing = expectedColumns.filter((col) => !present.has(col));

  if (missing.length > 0) {
    throw new Error(
      `Schema validation failed for ${tableName}. Missing columns: ${missing.join(', ')}`,
    );
  }
}

function createSchema(database: Database.Database): void {
  database.exec(`
    CREATE TABLE IF NOT EXISTS chats (
      jid TEXT PRIMARY KEY,
      name TEXT,
      last_message_time TEXT,
      channel TEXT,
      is_group INTEGER DEFAULT 0
    );
    CREATE TABLE IF NOT EXISTS messages (
      id TEXT,
      chat_jid TEXT,
      sender TEXT,
      sender_name TEXT,
      content TEXT,
      timestamp TEXT,
      is_from_me INTEGER,
      is_bot_message INTEGER DEFAULT 0,
      PRIMARY KEY (id, chat_jid),
      FOREIGN KEY (chat_jid) REFERENCES chats(jid)
    );
    CREATE INDEX IF NOT EXISTS idx_timestamp ON messages(timestamp);

    CREATE TABLE IF NOT EXISTS scheduled_tasks (
      id TEXT PRIMARY KEY,
      group_folder TEXT NOT NULL,
      chat_jid TEXT NOT NULL,
      prompt TEXT NOT NULL,
      schedule_type TEXT NOT NULL,
      schedule_value TEXT NOT NULL,
      next_run TEXT,
      last_run TEXT,
      last_result TEXT,
      status TEXT DEFAULT 'active',
      created_at TEXT NOT NULL
    );
    CREATE INDEX IF NOT EXISTS idx_next_run ON scheduled_tasks(next_run);
    CREATE INDEX IF NOT EXISTS idx_status ON scheduled_tasks(status);

    CREATE TABLE IF NOT EXISTS task_run_logs (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      task_id TEXT NOT NULL,
      run_at TEXT NOT NULL,
      duration_ms INTEGER NOT NULL,
      status TEXT NOT NULL,
      result TEXT,
      error TEXT,
      FOREIGN KEY (task_id) REFERENCES scheduled_tasks(id)
    );
    CREATE INDEX IF NOT EXISTS idx_task_run_logs ON task_run_logs(task_id, run_at);

    CREATE TABLE IF NOT EXISTS router_state (
      key TEXT PRIMARY KEY,
      value TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS sessions (
      group_folder TEXT PRIMARY KEY,
      session_id TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS registered_groups (
      jid TEXT PRIMARY KEY,
      name TEXT NOT NULL,
      folder TEXT NOT NULL UNIQUE,
      trigger_pattern TEXT NOT NULL,
      added_at TEXT NOT NULL,
      container_config TEXT,
      requires_trigger INTEGER DEFAULT 1
    );
  `);

  // Add context_mode column if it doesn't exist (migration for existing DBs)
  try {
    database.exec(
      `ALTER TABLE scheduled_tasks ADD COLUMN context_mode TEXT DEFAULT 'isolated'`,
    );
  } catch {
    /* column already exists */
  }

  // Add script column if it doesn't exist (migration for existing DBs)
  try {
    database.exec(`ALTER TABLE scheduled_tasks ADD COLUMN script TEXT`);
  } catch {
    /* column already exists */
  }

  // Add is_bot_message column if it doesn't exist (migration for existing DBs)
  try {
    database.exec(
      `ALTER TABLE messages ADD COLUMN is_bot_message INTEGER DEFAULT 0`,
    );
    // Backfill: mark existing bot messages that used the content prefix pattern
    database
      .prepare(`UPDATE messages SET is_bot_message = 1 WHERE content LIKE ?`)
      .run(`${ASSISTANT_NAME}:%`);
  } catch {
    /* column already exists */
  }

  // Add is_main column if it doesn't exist (migration for existing DBs)
  try {
    database.exec(
      `ALTER TABLE registered_groups ADD COLUMN is_main INTEGER DEFAULT 0`,
    );
    // Backfill: existing rows with folder = 'main' are the main group
    database.exec(
      `UPDATE registered_groups SET is_main = 1 WHERE folder = 'main'`,
    );
  } catch {
    /* column already exists */
  }

  // Add listen_only column if it doesn't exist (migration for existing DBs)
  // listen_only groups store messages passively but never spawn agent containers
  try {
    database.exec(
      `ALTER TABLE registered_groups ADD COLUMN listen_only INTEGER DEFAULT 0`,
    );
  } catch {
    /* column already exists */
  }

  // Create central brain table (intelligence across all groups)
  database.exec(`
    CREATE TABLE IF NOT EXISTS brain_entries (
      id TEXT PRIMARY KEY,
      source_group TEXT NOT NULL,
      entry_type TEXT NOT NULL,
      content TEXT NOT NULL,
      status TEXT DEFAULT 'open',
      created_at TEXT NOT NULL,
      updated_at TEXT,
      metadata TEXT
    );
    CREATE INDEX IF NOT EXISTS idx_brain_type ON brain_entries(entry_type);
    CREATE INDEX IF NOT EXISTS idx_brain_source ON brain_entries(source_group);
    CREATE INDEX IF NOT EXISTS idx_brain_status ON brain_entries(status);
    CREATE INDEX IF NOT EXISTS idx_brain_created ON brain_entries(created_at);
  `);

  // Add channel and is_group columns if they don't exist (migration for existing DBs)
  try {
    database.exec(`ALTER TABLE chats ADD COLUMN channel TEXT`);
    database.exec(`ALTER TABLE chats ADD COLUMN is_group INTEGER DEFAULT 0`);
    // Backfill from JID patterns
    database.exec(
      `UPDATE chats SET channel = 'whatsapp', is_group = 1 WHERE jid LIKE '%@g.us'`,
    );
    database.exec(
      `UPDATE chats SET channel = 'whatsapp', is_group = 0 WHERE jid LIKE '%@s.whatsapp.net'`,
    );
    database.exec(
      `UPDATE chats SET channel = 'discord', is_group = 1 WHERE jid LIKE 'dc:%'`,
    );
    database.exec(
      `UPDATE chats SET channel = 'telegram', is_group = 0 WHERE jid LIKE 'tg:%'`,
    );
  } catch {
    /* columns already exist */
  }

  // Add session health columns for Phase 0C session hygiene.
  // Tracks consecutive agent errors per group to implement controlled backoff.
  try {
    database.exec(
      `ALTER TABLE sessions ADD COLUMN error_count INTEGER DEFAULT 0`,
    );
  } catch {
    /* column already exists */
  }
  try {
    database.exec(`ALTER TABLE sessions ADD COLUMN last_error_at TEXT`);
  } catch {
    /* column already exists */
  }
  try {
    database.exec(`ALTER TABLE sessions ADD COLUMN backoff_until TEXT`);
  } catch {
    /* column already exists */
  }

  // Add reply context columns for quoted message rendering
  try {
    database.exec(`ALTER TABLE messages ADD COLUMN reply_to_message_id TEXT`);
  } catch {
    /* column already exists */
  }
  try {
    database.exec(
      `ALTER TABLE messages ADD COLUMN reply_to_message_content TEXT`,
    );
  } catch {
    /* column already exists */
  }
  try {
    database.exec(
      `ALTER TABLE messages ADD COLUMN reply_to_sender_name TEXT`,
    );
  } catch {
    /* column already exists */
  }

  // Validate expected schema after migrations so partial ALTER failures
  // surface immediately instead of causing runtime errors later.
  assertColumnsExist(database, 'scheduled_tasks', ['context_mode', 'script']);
  assertColumnsExist(database, 'messages', ['is_bot_message']);
  assertColumnsExist(database, 'registered_groups', [
    'requires_trigger',
    'is_main',
    'listen_only',
  ]);
  assertColumnsExist(database, 'chats', ['channel', 'is_group']);
}

export function initDatabase(): void {
  const dbPath = path.join(STORE_DIR, 'messages.db');
  fs.mkdirSync(path.dirname(dbPath), { recursive: true });

  db = new Database(dbPath);
  createSchema(db);

  // Migrate from JSON files if they exist
  migrateJsonState();
}

